"""Export a trained SNN checkpoint to an HLS C++ weights header + golden test vectors.

Runs a pure-integer NumPy reference (the spec the C++/RTL must match bit-for-bit),
checks it agrees with the PyTorch model, then writes:
  <out>/snn_weights.h     ternary weights as pos/neg bitmasks + all hyperparameters
  <out>/test_vectors.txt  one line per test image: levels, label, golden pred, golden counts

Usage:
  python export.py --ckpt ckpt_8x8_h24_v6_e30.pt --hidden 24 --theta 8 4 --leak 4 4 --vbits 6 --out hls
  python export.py --ckpt ckpt_8x8_h0_v8_e30.pt  --hidden 0  --theta 8   --leak 4   --vbits 8 --out hls_h0
"""
import argparse
from pathlib import Path

import numpy as np
import torch
from torchvision import datasets

from snn_model import SNN, preprocess, rate_encode

DATA = Path(__file__).resolve().parent / "data"


def rate_encode_np(levels, T, period=4):
    """levels (N,P) -> spikes (T,N,P) uint8. Pixel at level q spikes when floor((t+1)q/4) > floor(tq/4)."""
    t = np.arange(T + 1).reshape(-1, 1, 1)
    acc = (t * levels[None]) // period
    return (acc[1:] > acc[:-1]).astype(np.int32)


def int_reference(levels, weights, theta, leak, vbits, T):
    """Bit-exact integer SNN. Returns spike counts (N, 10)."""
    vmin, vmax = -(1 << (vbits - 1)), (1 << (vbits - 1)) - 1
    spikes = rate_encode_np(levels, T)
    n = levels.shape[0]
    v = [np.zeros((n, w.shape[0]), dtype=np.int32) for w in weights]
    counts = np.zeros((n, weights[-1].shape[0]), dtype=np.int32)
    for t in range(T):
        s = spikes[t]
        for i, w in enumerate(weights):
            v[i] = v[i] - (v[i] >> leak[i])                      # arithmetic shift leak
            v[i] = np.clip(v[i] + s @ w.T, vmin, vmax)            # full sum, then saturate once
            z = (v[i] >= theta[i]).astype(np.int32)
            v[i] = v[i] - z * theta[i]                            # subtractive reset
            s = z
        counts += s
    return counts


def masks(w):
    """Ternary weight matrix (out, in) -> per-neuron (pos_mask, neg_mask) ints; bit j = input j."""
    pos = [sum(1 << j for j in range(w.shape[1]) if w[i, j] == 1) for i in range(w.shape[0])]
    neg = [sum(1 << j for j in range(w.shape[1]) if w[i, j] == -1) for i in range(w.shape[0])]
    return pos, neg


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", required=True)
    ap.add_argument("--size", type=int, default=8)
    ap.add_argument("--hidden", type=int, default=24, help="0 = single layer")
    ap.add_argument("--theta", type=int, nargs="+", default=[8, 4])
    ap.add_argument("--leak", type=int, nargs="+", default=[4, 4])
    ap.add_argument("--vbits", type=int, default=6)
    ap.add_argument("--T", type=int, default=16)
    ap.add_argument("--out", default="hls")
    args = ap.parse_args()

    hidden = (args.hidden,) if args.hidden else ()
    model = SNN(args.size ** 2, hidden, theta=args.theta, leak=args.leak, vbits=args.vbits)
    model.load_state_dict(torch.load(args.ckpt, map_location="cpu"))
    model.eval()
    weights = [l.fc.ternary().detach().round().long().numpy() for l in model.layers]

    te = datasets.MNIST(DATA, train=False, download=True)
    levels = preprocess(te.data, args.size)
    labels = te.targets.numpy()

    ref_counts = int_reference(levels.numpy().astype(np.int32), weights, args.theta, args.leak, args.vbits, args.T)
    with torch.no_grad():
        torch_counts = torch.cat([model(rate_encode(levels[i:i + 2000], args.T))
                                  for i in range(0, len(levels), 2000)]).long().numpy()
    assert np.array_equal(ref_counts, torch_counts), "integer reference disagrees with PyTorch model"
    preds = ref_counts.argmax(1)  # first max wins ties
    acc = (preds == labels).mean()
    print(f"Integer reference == PyTorch on all {len(labels)} images. Test accuracy {acc:.4%}")

    out = Path(args.out)
    out.mkdir(exist_ok=True)
    n_in, n_out = args.size ** 2, 10
    nz = [int((w != 0).sum()) for w in weights]
    lines = [
        "// AUTO-GENERATED by export.py -- do not edit.",
        f"// Source checkpoint: {Path(args.ckpt).name}   integer-reference test accuracy: {acc:.4%}",
        f"// Non-zero ternary weights per layer: {nz}",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define SNN_IN     {n_in}   // input pixels ({args.size}x{args.size}), bit p = row*{args.size}+col",
        f"#define SNN_IW     {(n_in + 63) // 64}   // 64-bit words per input spike vector",
        f"#define SNN_H      {args.hidden}   // hidden LIF neurons (0 = single layer)",
        f"#define SNN_OUT    {n_out}",
        f"#define SNN_T      {args.T}   // timesteps per inference",
        f"#define SNN_VBITS  {args.vbits}   // signed membrane width (saturating)",
        f"#define SNN_VMIN   ({-(1 << (args.vbits - 1))})",
        f"#define SNN_VMAX   ({(1 << (args.vbits - 1)) - 1})",
    ]
    for i in range(len(weights)):
        lines += [f"#define SNN_THETA{i + 1} {args.theta[i]}", f"#define SNN_LEAK{i + 1}  {args.leak[i]}   // v -= v >>> LEAK"]
    lines.append("")
    for i, w in enumerate(weights):
        pos, neg = masks(w)
        for name, m in (("POS", pos), ("NEG", neg)):
            sign = "+1" if name == "POS" else "-1"
            if i == 0:  # input layer: SNN_IW 64-bit words per neuron, word k holds inputs 64k..64k+63
                nw = (w.shape[1] + 63) // 64
                rows = ["{" + ", ".join(f"0x{(x >> (64 * k)) & (2 ** 64 - 1):016X}ULL" for k in range(nw)) + "}"
                        for x in m]
                body = ",\n    ".join(rows)
                lines.append(f"// Layer 1 {name}: bit (j % 64) of word (j / 64) set => weight[n][j] = {sign}")
                lines.append(f"static const uint64_t W1_{name}[{w.shape[0]}][SNN_IW] = {{\n    {body}\n}};")
            else:
                body = ",\n    ".join(f"0x{x:08X}U" for x in m)
                lines.append(f"// Layer {i + 1} {name}: bit j set => weight[n][j] = {sign}")
                lines.append(f"static const uint32_t W{i + 1}_{name}[{w.shape[0]}] = {{\n    {body}\n}};")
    (out / "snn_weights.h").write_text("\n".join(lines) + "\n")

    with open(out / "test_vectors.txt", "w") as f:
        f.write(f"# levels({n_in} digits 0-3, pixel 0 first) label golden_pred golden_counts[10]\n")
        for lv, y, p, c in zip(levels.numpy(), labels, preds, ref_counts):
            f.write("".join(map(str, lv)) + f" {y} {p} " + " ".join(map(str, c)) + "\n")
    np.savez(out / "weights_ternary.npz", *weights)
    print(f"Wrote {out / 'snn_weights.h'}, {out / 'test_vectors.txt'}, {out / 'weights_ternary.npz'}")


if __name__ == "__main__":
    main()
