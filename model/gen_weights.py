"""Generate ../src/snn_weights.v (hardwired ternary weight lookup) from the exported model.

Usage: python model/gen_weights.py [weights_ternary.npz]

Encoding: 2-bit two's complement  00 = 0, 01 = +1, 11 = -1.
  snn_w: addr = {neuron[3:0], pixel[5:0]}   (10 x 64; pixel = 8*byte + bit)
Only non-zero entries are listed; everything else (incl. unused addresses) is 0.
"""
import sys
from pathlib import Path

import numpy as np

here = Path(__file__).resolve().parent
src = Path(sys.argv[1]) if len(sys.argv) > 1 else here / "weights_ternary.npz"
d = np.load(src)
assert len(d.files) == 1, "expected a single-layer model (64 -> 10)"
w = d["arr_0"]
assert w.shape == (10, 64)

enc = {1: "2'b01", -1: "2'b11"}
entries = [((n << 6) | p, int(w[n, p])) for n in range(10) for p in range(64) if w[n, p] != 0]

out = ["// AUTO-GENERATED by gen_weights.py from " + src.name + " -- do not edit.",
       "// Ternary weights, 2-bit two's complement: 01 = +1, 11 = -1, 00 = 0.",
       "`default_nettype none",
       "",
       f"// addr = {{neuron[3:0], pixel[5:0]}}, {len(entries)} non-zero of 640",
       "module snn_w (",
       "    input  wire [9:0] addr,",
       "    output reg  [1:0] w",
       ");",
       "  always @(*) begin",
       "    case (addr)"]
out += [f"      10'd{a}: w = {enc[v]};" for a, v in entries]
out += ["      default: w = 2'b00;", "    endcase", "  end", "endmodule", ""]
(here.parent / "src" / "snn_weights.v").write_text("\n".join(out))
print(f"wrote src/snn_weights.v  ({len(entries)} non-zero of 640)")
