"""Generate ../src/snn_weights.v (hardwired ternary weight lookup) from the exported model.

Usage: python model/gen_weights.py [weights_ternary.npz]

Encoding: 2-bit two's complement  00 = 0, 01 = +1, 11 = -1.
  snn_w1: addr = {neuron[4:0], pixel[5:0]}   (24 x 64)
  snn_w2: addr = {hidden[4:0], output[3:0]}  (10 x 24, indexed by hidden neuron first)
Only non-zero entries are listed; everything else (incl. unused addresses) is 0.
"""
import sys
from pathlib import Path

import numpy as np

here = Path(__file__).resolve().parent
src = Path(sys.argv[1]) if len(sys.argv) > 1 else here / "weights_ternary.npz"
d = np.load(src)
w1, w2 = d["arr_0"], d["arr_1"]  # (24, 64), (10, 24)
assert w1.shape == (24, 64) and w2.shape == (10, 24)

enc = {1: "2'b01", -1: "2'b11"}


def lut(name, abits, entries, comment):
    lines = [f"// {comment}",
             f"module {name} (",
             f"    input  wire [{abits - 1}:0] addr,",
             "    output reg  [1:0] w",
             ");",
             "  always @(*) begin",
             "    case (addr)"]
    lines += [f"      {abits}'d{a}: w = {enc[v]};" for a, v in entries]
    lines += ["      default: w = 2'b00;", "    endcase", "  end", "endmodule", ""]
    return lines


e1 = [((n << 6) | p, int(w1[n, p])) for n in range(24) for p in range(64) if w1[n, p] != 0]
e2 = [((j << 4) | k, int(w2[k, j])) for j in range(24) for k in range(10) if w2[k, j] != 0]

out = ["// AUTO-GENERATED by gen_weights.py from " + src.name + " -- do not edit.",
       "// Ternary weights, 2-bit two's complement: 01 = +1, 11 = -1, 00 = 0.",
       "`default_nettype none", ""]
out += lut("snn_w1", 11, e1, f"Layer 1: addr = {{neuron[4:0], pixel[5:0]}}, {len(e1)} non-zero of 1536")
out += lut("snn_w2", 9, e2, f"Layer 2: addr = {{hidden[4:0], output[3:0]}}, {len(e2)} non-zero of 240")
(here.parent / "src" / "snn_weights.v").write_text("\n".join(out))
print(f"wrote src/snn_weights.v  (layer1 {len(e1)} nz, layer2 {len(e2)} nz)")
